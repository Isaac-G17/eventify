-- V2: Evolución relacional
--   * Venue: nueva columna obligatoria ciudad
--   * Event: borrado lógico (activo) y relación Many-to-One obligatoria con Venue
--   * Category: nueva entidad + tabla intermedia events_categories (Many-to-Many)

ALTER TABLE venues ADD COLUMN ciudad VARCHAR(100) NOT NULL;

ALTER TABLE events ADD COLUMN activo BOOLEAN DEFAULT TRUE NOT NULL;
ALTER TABLE events ADD COLUMN venue_id BIGINT NOT NULL;
ALTER TABLE events ADD CONSTRAINT fk_events_venue FOREIGN KEY (venue_id) REFERENCES venues (id);

CREATE TABLE categories (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(100) NOT NULL,
    descripcion  VARCHAR(250) NOT NULL,
    CONSTRAINT uk_categories_nombre UNIQUE (nombre)
);

CREATE TABLE events_categories (
    event_id     BIGINT NOT NULL,
    category_id  BIGINT NOT NULL,
    CONSTRAINT pk_events_categories PRIMARY KEY (event_id, category_id),
    CONSTRAINT fk_events_categories_event FOREIGN KEY (event_id) REFERENCES events (id),
    CONSTRAINT fk_events_categories_category FOREIGN KEY (category_id) REFERENCES categories (id)
);

-- Índices para los filtros y el ordenamiento del catálogo
CREATE INDEX idx_events_fecha ON events (fecha);
CREATE INDEX idx_events_venue ON events (venue_id);
CREATE INDEX idx_venues_ciudad ON venues (ciudad);
